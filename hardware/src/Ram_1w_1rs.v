// Adapter for the SpinalHDL VexRiscv memory blackbox interface `Ram_1w_1rs`
// (1 write port + 1 read port, one cycle registered read). It maps the
// blackbox onto the py2hwsw `iob_ram_t2p` / `iob_ram_t2p_be` memories, so the
// VexRiscv internal memories (register file, instruction/data caches) use the
// same simulation/FPGA/ASIC-compatible primitives as the rest of the design.
//
// `Ram_1w_1rs` is emitted by VexRiscv when memory blackboxing is enabled
// (`blackboxAllWhatsYouCan`). No implementation is generated by SpinalHDL, so
// this module provides it.
//
// The MEM_ASIC parameter selects the ASIC (sky130 hard macro) implementation.
// It is 0 by default so that simulation/FPGA builds use the behavioral model.
// The ASIC flow defines IOB_MEM_ASIC (see asic_config_gen.py) to enable the
// hard macros.

`ifdef IOB_MEM_ASIC
`define RAM_1W_1RS_MEM_ASIC_DEFAULT 1
`else
`define RAM_1W_1RS_MEM_ASIC_DEFAULT 0
`endif

module Ram_1w_1rs #(
    parameter wordCount      = 32,
    parameter wordWidth      = 32,
    parameter clockCrossing  = 1'b0,
    parameter technology     = "auto",
    parameter readUnderWrite = "dontCare",
    parameter wrAddressWidth = 5,
    parameter wrDataWidth    = 32,
    parameter wrMaskWidth    = 1,
    parameter wrMaskEnable   = 1'b0,
    parameter rdAddressWidth = 5,
    parameter rdDataWidth    = 32,
    parameter rdLatency      = 1,
    parameter MEM_ASIC       = `RAM_1W_1RS_MEM_ASIC_DEFAULT
) (
    input  wire                      wr_clk,
    input  wire                      wr_en,
    input  wire [  wrMaskWidth-1:0]  wr_mask,
    input  wire [wrAddressWidth-1:0] wr_addr,
    input  wire [  wrDataWidth-1:0]  wr_data,
    input  wire                      rd_clk,
    input  wire                      rd_en,
    input  wire [rdAddressWidth-1:0] rd_addr,
    input  wire                      rd_dataEn,
    output wire [  rdDataWidth-1:0]  rd_data
);

  // The word count of every blackboxed VexRiscv memory is a power of two.
  localparam ADDR_W = $clog2(wordCount);

  // The RTL memories have a single clock and a one cycle registered read,
  // matching the generated VexRiscv memories (clockCrossing = 0, rdLatency =
  // 1).
  generate
    if (wrMaskEnable) begin : g_byte_enable
      iob_ram_t2p_be #(
          .ADDR_W(ADDR_W),
          .DATA_W(wrDataWidth),
          .MEM_ASIC(MEM_ASIC),
          .SIMULATION(!MEM_ASIC)
      ) ram (
          .clk_i(wr_clk),
          .w_strb_i(wr_mask),
          .w_addr_i(wr_addr),
          .w_data_i(wr_data),
          .r_en_i(rd_en & rd_dataEn),
          .r_addr_i(rd_addr),
          .r_data_o(rd_data)
      );
    end else begin : g_single_enable
      iob_ram_t2p #(
          .ADDR_W(ADDR_W),
          .DATA_W(wrDataWidth),
          .MEM_ASIC(MEM_ASIC),
          .SIMULATION(!MEM_ASIC)
      ) ram (
          .clk_i(wr_clk),
          .w_en_i(wr_en),
          .w_addr_i(wr_addr),
          .w_data_i(wr_data),
          .r_en_i(rd_en & rd_dataEn),
          .r_addr_i(rd_addr),
          .r_data_o(rd_data)
      );
    end
  endgenerate

endmodule
